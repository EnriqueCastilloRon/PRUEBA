def on_load_case(change):
    uploaded = change['new']
    if not uploaded:
        return

    # Manejar diferentes estructuras de 'uploaded'
    if isinstance(uploaded, dict):
        # Las claves son los nombres de archivo
        first_filename = list(uploaded.keys())[0]
        file_info = uploaded[first_filename]
    else:
        # Es una lista
        file_info = uploaded[0]
        # Intentar obtener el nombre
        if isinstance(file_info, dict):
            first_filename = file_info.get('name') or file_info.get('metadata', {}).get('name', 'archivo.csv')
        else:
            first_filename = 'archivo.csv'

    # Extraer el contenido binario
    content = None
    if isinstance(file_info, dict):
        content = file_info.get('content')
        if content is None:
            content = file_info.get('data')
    else:
        content = file_info

    if content is None:
        print("No se pudo leer el contenido del archivo.")
        # Opcional: imprimir la estructura para depuración
        print("Estructura recibida:", file_info)
        return

    try:
        df_new = load_and_prepare_data(content)
        set_new_data(df_new)
        print(f"Archivo '{first_filename}' cargado correctamente. {len(df_new)} registros.")
        # Reiniciar sliders
        center_slider.value = 0.5
        threshold_slider.value = 0.2
        min_opacity_slider.value = 0.1
    except Exception as e:
        print(f"Error al cargar el archivo: {e}")

