def update_plots(centro, umbral, min_opacity):
    global current_fig, df_global, raw_alpha
    if df_global is None or raw_alpha is None:
        load_default_data()
        if df_global is None:
            print("Error: No se pudieron cargar los datos.")
            return

    mascara = (raw_alpha >= centro - umbral) & (raw_alpha <= centro + umbral)
    alphas = np.full(len(df_global), min_opacity)
    if np.any(mascara):
        alpha_visible = raw_alpha[mascara]
        if alpha_visible.max() > alpha_visible.min():
            alpha_rescaled = (alpha_visible - alpha_visible.min()) / (alpha_visible.max() - alpha_visible.min())
            alphas[mascara] = min_opacity + (1 - min_opacity) * alpha_rescaled
        else:
            alphas[mascara] = 0.8

    point_size = 20
    fig, axes = plt.subplots(2, 3, figsize=(15, 10))
    current_fig = fig

    # Gráfico 1
    axes[0,0].scatter(df_global['N'], df_global['sigmaM'], alpha=alphas, s=point_size, c='blue')
