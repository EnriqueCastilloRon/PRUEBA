def prepare_dataframe(df):
    global raw_alpha
    df['sigma_m'] = df['R'] * df['sigmaM']
    df['X'] = 1 - df['R']
    min_sigmam = df['sigma_m'].min()
    max_sigmam = df['sigma_m'].max()
    if max_sigmam == min_sigmam:
        df['Y'] = 0.0
    else:
        df['Y'] = (df['sigma_m'] - min_sigmam) / (max_sigmam - min_sigmam)
    min_sM = df['sigmaM'].min()
    max_sM = df['sigmaM'].max()
    if max_sM == min_sM:
        raw_alpha = np.zeros(len(df))
    else:
        raw_alpha = (df['sigmaM'] - min_sM) / (max_sM - min_sM)
    return df

def load_and_prepare_data(file_content):
    if isinstance(file_content, bytes):
        file_content = file_content.decode('utf-8')
    df = pd.read_csv(StringIO(file_content))
    required_cols = {'R', 'sigmaM', 'N'}
    if not required_cols.issubset(df.columns):
        raise ValueError(f"El archivo debe contener las columnas: {required_cols}")
    df = prepare_dataframe(df)
    return df

def set_new_data(df_new):
    global df_global, raw_alpha
    df_global = df_new.copy()

def load_default_data():
    global df_global, raw_alpha
    df = pd.read_csv(StringIO(DEFAULT_CSV_DATA))
    df = prepare_dataframe(df)
    df_global = df
    print("Dataset por defecto cargado correctamente.")

